"""Implementation of Rule LT05."""

from collections.abc import Iterator
from typing import cast

from sqlfluff.core.parser import BaseSegment
from sqlfluff.core.parser.segments import TemplateSegment
from sqlfluff.core.rules import LintResult, RuleContext
from sqlfluff.core.rules.base import BaseRule
from sqlfluff.core.rules.crawlers import RootOnlyCrawler
from sqlfluff.utils.reflow.sequence import ReflowSequence


class Rule_LT05(BaseRule):
    """Line is too long."""

    name = "layout.long_lines"
    aliases = ("L016",)
    groups = ("all", "core", "layout")
    crawl_behaviour = RootOnlyCrawler()
    targets_templated = True
    template_safe_fixes = True
    _adjust_anchors = True
    _check_docstring = False
    is_fix_compatible = True

    config_keywords = [
        "ignore_comment_lines",
        "ignore_comment_clauses",
        "ignore_aliases",
    ]

    @staticmethod
    def _iter_line_segments_with_ancestor(
        context: RuleContext,
        result: LintResult,
        ancestor_types: tuple[str, ...],
    ) -> Iterator[tuple[BaseSegment, BaseSegment | None]]:
        """Yield raw segments on a result line and a matching ancestor."""
        assert result.anchor
        assert result.anchor.pos_marker
        assert result.anchor.is_type("raw"), (
            "Expected fixes generated by `break_long_lines` to only have "
            "`RawSegment` anchors."
        )
        raw_segments = context.segment.raw_segments
        raw_idx = context.segment.raw_segment_index(result.anchor)
        for seg in raw_segments[raw_idx:]:
            assert seg.pos_marker
            if (
                seg.pos_marker.working_line_no
                != result.anchor.pos_marker.working_line_no
            ):
                break
            ancestor = next(
                (
                    path_step.segment
                    for path_step in context.segment.path_to(seg)
                    if path_step.segment.is_type(*ancestor_types)
                ),
                None,
            )
            yield seg, ancestor

    def _eval(self, context: RuleContext) -> list[LintResult]:
        """Line is too long."""
        self.ignore_comment_lines: bool
        self.ignore_comment_clauses: bool
        self.ignore_aliases: bool
        # Reflow and generate fixes.
        results = (
            ReflowSequence.from_root(context.segment, context.config)
            .break_long_lines()
            .get_results()
        )

        # Ignore any comment line if appropriate.
        if self.ignore_comment_lines:
            raw_segments = context.segment.raw_segments
            for res in results[:]:
                # First handle the easy case that the anchor (i.e. the start
                # of the line is a comment).
                assert res.anchor
                assert res.anchor.pos_marker
                assert res.anchor.is_type("raw"), (
                    "Expected fixes generated by `break_long_lines` to only have "
                    "`RawSegment` anchors."
                )
                if res.anchor.is_type("comment"):
                    self.logger.debug(
                        "Purging result on long line starting with comment: %s",
                        res.anchor.pos_marker.working_line_no,
                    )
                    results.remove(res)
                    continue
                # Then look for comments on the rest of the line:
                assert res.anchor.pos_marker
                raw_idx = context.segment.raw_segment_index(res.anchor)
                for seg_idx in range(raw_idx, len(raw_segments)):
                    seg = raw_segments[seg_idx]
                    if (
                        seg.pos_marker.working_line_no
                        != res.anchor.pos_marker.working_line_no
                    ):
                        # We've gone past the end of the line. Stop looking.
                        break  # pragma: no cover
                    # Is it a comment?
                    if seg.is_type("comment"):
                        self.logger.debug(
                            "Purging result on long line containing comment: %s",
                            res.anchor.pos_marker.working_line_no,
                        )
                        results.remove(res)
                        break
                    # Is it a template comment?
                    elif (
                        seg.is_type("placeholder")
                        and cast(TemplateSegment, seg).block_type == "comment"
                    ):
                        self.logger.debug(
                            "Purging result with template comment line: %s",
                            res.anchor.pos_marker.working_line_no,
                        )
                        results.remove(res)
                        break

        # Ignore any comment clauses if present.
        if self.ignore_comment_clauses:
            for res in results[:]:
                assert res.anchor
                assert res.anchor.pos_marker
                for _, clause in self._iter_line_segments_with_ancestor(
                    context,
                    res,
                    ("comment_clause", "comment_equals_clause"),
                ):
                    if clause is None:
                        continue
                    assert clause.pos_marker
                    line_pos = clause.pos_marker.working_line_pos
                    if line_pos < context.config.get("max_line_length"):
                        self.logger.debug(
                            "Purging result on long line with comment clause: %s",
                            res.anchor.pos_marker.working_line_no,
                        )
                        results.remove(res)
                    else:
                        self.logger.debug(
                            "Keeping result on long line with comment clause. "
                            "Still too long without comment: %s",
                            res.anchor.pos_marker.working_line_no,
                        )
                    break

        # Ignore aliases which begin within the configured line length. This
        # supports projects which align aliases at a fixed column and do not
        # include the alias itself when enforcing the line length.
        if self.ignore_aliases:
            max_line_length = context.config.get("max_line_length")
            for res in results[:]:
                assert res.anchor
                assert res.anchor.pos_marker
                alias_overflows = False
                unrelated_overflow = False
                for line_seg, alias_segment in self._iter_line_segments_with_ancestor(
                    context, res, ("alias_expression",)
                ):
                    assert line_seg.pos_marker
                    segment_end = (
                        line_seg.pos_marker.working_line_pos + len(line_seg.raw) - 1
                    )
                    if segment_end <= max_line_length:
                        continue
                    if alias_segment is not None:
                        assert alias_segment.pos_marker
                        if alias_segment.pos_marker.working_line_pos <= max_line_length:
                            alias_overflows = True
                            continue
                    if not line_seg.is_type(
                        "whitespace",
                        "newline",
                        "indent",
                        "dedent",
                        "end_of_file",
                        "comma",
                        "semicolon",
                    ):
                        unrelated_overflow = True
                        break
                if alias_overflows and not unrelated_overflow:
                    self.logger.debug(
                        "Purging result on long line ending with alias: %s",
                        res.anchor.pos_marker.working_line_no,
                    )
                    results.remove(res)

        return results
